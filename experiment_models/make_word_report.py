def chart_metrics(m1, m4, m4b, m5):
    labels = [DISPLAY[k] for k in ORDER]
    metrics = [
        ('Термины EN↔RU', [m1[k]['top1_acc'] for k in ORDER]),
        ('Точность темы*', [m4[k]['loo_top1'] for k in ORDER]),
        ('Чистота окружения', [m4b[k]['knn_purity_10'] for k in ORDER]),
        ('Восстановление тем (ARI)', [m4b[k]['kmeans_ari'] for k in ORDER]),
        ('Узнаваемость сканов', [m5[k]['id_top1'] for k in ORDER]),
    ]
    x = np.arange(len(labels))
    width = 0.16
    fig, ax = plt.subplots(figsize=(10, 4.6))
    for i, (name, vals) in enumerate(metrics):
        bars = ax.bar(x + (i - 2) * width, vals, width, label=name)
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v + 0.01, f"{v:.2f}",
                    ha='center', va='bottom', fontsize=6.5, rotation=90)
    ax.set_ylim(0, 1.0)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, fontsize=9)
    ax.set_ylabel('доля / индекс (0–1)')
    ax.set_title('Ключевые показатели качества по моделям '
                 '(* — с форовым преимуществом v1.5)', fontsize=12)
    ax.legend(fontsize=8, ncol=2, loc='lower right')
    ax.grid(axis='y', alpha=0.3)
    fig.tight_layout()
    out = CHARTS_DIR / 'chart_metrics.png'
    fig.savefig(out, dpi=200)
    plt.close(fig)
    return out


