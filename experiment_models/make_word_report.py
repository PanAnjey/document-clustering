def shade_cell(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:fill'), fill)
    tcPr.append(shd)


def set_cell(cell, text, bold=False, color=None, align='center', size=9):
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = {'center': WD_ALIGN_PARAGRAPH.CENTER,
                   'left': WD_ALIGN_PARAGRAPH.LEFT}[align]
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def add_table(doc, headers, rows, best_cols=None, align_first_left=True):
    """best_cols: {col_idx: 'max'|'min'} — подсветка лучшего значения."""
    best_cols = best_cols or {}
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    try:
        table.style = 'Light Shading Accent 1'
    except KeyError:
        table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        set_cell(table.rows[0].cells[j], h, bold=True)
    # лучшие значения
    best = {}
    for j, mode in best_cols.items():
        vals = [r[j] for r in rows]
        best[j] = max(vals) if mode == 'max' else min(vals)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            is_best = j in best and v == best[j]
            text = v if isinstance(v, str) else (pct(v) if isinstance(v, float)
                                                 and v <= 1.0 else str(v))
            set_cell(table.rows[i + 1].cells[j], text, bold=is_best,
                     color=GREEN if is_best else None,
                     align='left' if (j == 0 and align_first_left) else 'center')
    return table


def add_note(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(8.5)
    run.font.italic = True
    run.font.color.rgb = GRAY
    return p


def add_body(doc, text, bold_prefix=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if bold_prefix:
        run = p.add_run(bold_prefix)
        run.font.bold = True
    p.add_run(text)
    return p


def add_bullet(doc, text, bold_prefix=None):
    p = doc.add_paragraph(style='List Bullet')
    if bold_prefix:
        run = p.add_run(bold_prefix)
        run.font.bold = True
    p.add_run(text)
    return p


def add_toc(doc):
    para = doc.add_paragraph()
    run = para.add_run()
    fld1 = OxmlElement('w:fldChar')
    fld1.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-2" \\h \\z \\u'
    fld2 = OxmlElement('w:fldChar')
    fld2.set(qn('w:fldCharType'), 'separate')
    t = OxmlElement('w:t')
    t.text = 'Оглавление обновляется в Word: выделить всё (Ctrl+A) → F9'
    fld3 = OxmlElement('w:fldChar')
    fld3.set(qn('w:fldCharType'), 'end')
    for el in (fld1, instr, fld2, t, fld3):
        run._r.append(el)


def add_page_number(footer_para):
    run = footer_para.add_run()
    fld1 = OxmlElement('w:fldChar')
    fld1.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.text = 'PAGE'
    fld2 = OxmlElement('w:fldChar')
    fld2.set(qn('w:fldCharType'), 'end')
    for el in (fld1, instr, fld2):
        run._r.append(el)


