def pair_label(pair: str) -> str:
    """«nomic_v15 vs nomic_v2» → «Nomic v1.5 (реф.) ↔ Nomic v2-moe»."""
    parts = pair.replace(' ↔ ', ' vs ').split(' vs ')
    return ' ↔ '.join(DISPLAY.get(p.strip(), p.strip()) for p in parts)


def pct(x, d=1):
    return f"{x * 100:.{d}f}%"


def f3(x):
    return f"{x:.3f}"


