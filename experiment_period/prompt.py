if os.environ.get('PROMPT_V') == '2':   # анализ чувствительности: без упоминания УПД/актов/заявок
    SYSTEM = SYSTEM.replace('- даты договоров, заказов, актов, УПД, заявок («по договору от 01.10.2013», «№ 5 от 26.12.2025») периодом НЕ являются;',
                            '- дата заключения договора («по договору от 01.10.2013») периодом оказания не является;')

RX = re.compile(r'(\d{4})-(\d{2})-(\d{2})\s*[—–\-]+\s*(\d{4})-(\d{2})-(\d{2})')


def parse(raw):
    """Ответ модели (после «ПЕРИОД:») -> [start, end] | None (нет) | 'bad' (не разобрано)."""
    raw = re.sub(r'<think>.*?</think>', '', raw, flags=re.S).strip()
    m = RX.search(raw)
    if m:
        g = m.groups(); return [f'{g[0]}-{g[1]}-{g[2]}', f'{g[3]}-{g[4]}-{g[5]}']
    m1 = re.search(r'(\d{4}-\d{2}-\d{2})', raw)
    if m1 and not re.match(r'\s*нет', raw, re.I): return [m1.group(1), m1.group(1)]
    if re.match(r'\s*(ПЕРИОД\s*:\s*)?нет', raw, re.I): return None
    return 'bad'
