_XML_DECL_RE = re.compile(r'<\?xml[^?]*\?>')
_WS_RE = re.compile(r'\s+')

# ── Очистка договорных ссылок и периодов из тематического текста (V3) ──
# "согласно ДС № DMC... от 19.08.2025 г.", "по Договору № Д25292 от 22.05.2025",
# "Договор АК-037.", ", договор № 31" — не несут тематики, но притягивают
# эмбеддинг к центроиду "вознаграждение по договору" (тема 26).
_CONTRACT_RE = re.compile(
    r'\s*,?\s*(?:по|согласно|в\s+рамках|к)?\s*'
    r'(?:договор(?:у|а|ом|е)?|дс|доп(?:\.|олнени(?:ю|ем|е|я))?|'
    r'соглашени(?:ю|е|я|ем|и)?)\s*'
    r'(?:№|N)?\s*'
    r'(?:[«"\w\-/\\.\[\]()]*\d[«"\w\-/\\.\[\]()]*\s*)+'  # 1+ токенов с цифрами
    r'(?:от\s+[\d.]+\s*г?\.?)?\s*[,.]?\s*',
    re.IGNORECASE)
# "за апрель 2026 г.", "за МАРТ-2026.", "за период с 01.03.2026 по 31.03.2026 г.",
# "в марте месяце 2026г.", "апрель 2026г"
_MONTHS = (r'январ[ьяею]?|феврал[ьяею]?|март[аеу]?|апрел[ьяею]?|ма[йяею]|'
           r'июн[ьяею]?|июл[ьяею]?|август[аеу]?|сентябр[ьяею]?|октябр[ьяею]?|'
           r'ноябр[ьяею]?|декабр[ьяею]?')
_PERIOD_RE = re.compile(
    r'\s*за\s+(?:период\s+)?(?:с\s+[\d.]+\s+по\s+[\d.]+\s*г?\.?|'
    r'(?:\w+-\w+|' + _MONTHS + r')[\s,.]*\d{0,4}\s*г?\.?)'
    r'|\s*в\s+(?:' + _MONTHS + r')\s+(?:месяце\s+)?\d{4}\s*г?\.?'
    r'|\s+(?:' + _MONTHS + r')\s+\d{4}\s*г?\.?',
    re.IGNORECASE)
_MULTI_COMMA_RE = re.compile(r'\s*[,;]\s*[,;.]+')
_SPACE_PUNCT_RE = re.compile(r'\s+([,;.])')

# ── Ритуальные фразы СодОпер (п.4 правок): не несут тематики ─────
_OPER_BOILERPLATE = (
    'товары переданы', 'услуги оказаны', 'работы выполнены', 'реализация',
    'стороны по объему', 'товары и услуги принял', 'регистрация счет-фактуры',
    'оказание услуг', 'товар (груз)', 'работы (услуги)', 'передача тов/раб/усл',
    'работы сданы', 'услуги оказаны.', '-', '—',
)


def _is_boilerplate_oper(oper):
    """СодОпер — ритуальная фраза без тематической ценности?"""
    if not oper:
        return True
    low = oper.lower().strip()
    for bp in _OPER_BOILERPLATE:
        if low.startswith(bp):
            return True
    return len(low) < 4


def strip_contract_refs(text):
    """Удалить договорные ссылки и календарные периоды из текста.

    Применяется к тематическому представлению (V2 → V3). Если после очистки
    остаётся <5 символов — возвращается исходный текст (безопасность).
    """
    if not text:
        return text
    s = text
    prev = None
    while prev != s:  # цепочки: "согласно ДС №... по Договору №..."
        prev = s
        s = _CONTRACT_RE.sub(' ', s)
    s = _PERIOD_RE.sub(' ', s)
    s = _MULTI_COMMA_RE.sub(', ', s)
    s = _SPACE_PUNCT_RE.sub(r'\1', s)
    s = _WS_RE.sub(' ', s).strip(' ,;.')
    return s if len(s) >= 5 else text


def _clean(s, maxlen=None):
    if s is None:
        return ''
    s = _WS_RE.sub(' ', str(s)).strip()
    if maxlen and len(s) > maxlen:
        s = s[:maxlen].rstrip()
    return s


def _norm_region(name):
    """Нормализация: 'г. Москва' → 'Москва', 'Респ Башкортостан' → 'Башкортостан'."""
    if not name:
        return ''
    s = _clean(name)
    s = re.sub(r'^(г\.?\s+|Респ\.?\s+|Республика\s+)', '', s, flags=re.IGNORECASE)
    for key in _REGION_TEXT_KEYS:
        if key in s.lower():
            return _REGION_KEY_TO_NAME.get(key, s)
    return s


def detect_region(addr_el):
    """Извлечь регион из элемента Адрес (АдрРФ/АдрГАР/АдрИнф)."""
    if addr_el is None:
        return ''
    adr_rf = addr_el.find('АдрРФ')
    if adr_rf is not None:
        code = _clean(adr_rf.get('КодРегион'))
        name = _clean(adr_rf.get('НаимРегион'))
        if code and code in REGION_BY_CODE:
            return REGION_BY_CODE[code]
        if name:
            return _norm_region(name)
    adr_gar = addr_el.find('АдрГАР')
    if adr_gar is not None:
        reg = adr_gar.find('Регион')
        name_el = adr_gar.find('НаимРегион')
        if name_el is not None and name_el.text:
            return _norm_region(name_el.text)
        if reg is not None and reg.text:
            code = _clean(reg.text)
            return REGION_BY_CODE.get(code, code)
    adr_inf = addr_el.find('АдрИнф')
    if adr_inf is not None:
        txt = (adr_inf.get('АдрТекст') or '').lower()
        for key in _REGION_TEXT_KEYS:
            if key in txt:
                return _REGION_KEY_TO_NAME.get(key, key)
    return ''


