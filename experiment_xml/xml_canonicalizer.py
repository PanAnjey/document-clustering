# UniversalTransferDocument / Invoice → компактный плоский текст для эмбеддинга.
#
# Принципы:
#   1. Белый список полей (шум: адреса банков, подписанты, маркировка, прослеж,
#      денежные поля строк — отбрасываются).
#   2. Словарь перекодировки TAG_DICT: длинные кириллические имена элементов
#      заменяются короткими токенами (Тип, Прод, Пок, Т1..T5, Осн, Доп1..3 ...).
#   3. Табличная часть — первые MAX_TABLE_ROWS строк СведТов.
#   4. ИнфПолФХЖ1/2/3 включаются ПОЛНОСТЬЮ (по договорённости с КА там может
#      быть структурированная привязка к документам-основаниям).
#   5. Адрес контрагента (продавца) + выделение региона.
#   6. ОснПер (документы-основания) включаются.
#
# Вход: xml_val как str (MySQL utf8mb4). Декларация encoding="windows-1251"
# в шапке — устаревшая, перед парсингом вырезается (см. AGENTS.md контекст).

