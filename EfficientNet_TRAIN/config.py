# ---- Resize / сохранение пропорций (используется при INPUT_MODE="full") ----
# ВАЖНО: ориентация определяется СОДЕРЖИМЫМ (направлением чтения текста), а НЕ формой
# листа. В каждом классе (0/90/180/270) законно встречаются и портретные, и альбомные
# документы — соотношение сторон НЕ определяет класс и не должно использоваться как
# решающий признак.
# letterbox: вписать с сохранением пропорций + поля. Выбран потому, что НЕ искажает
#            содержимое (squash растягивает текст/линии и портит распознавание
#            направления чтения). Возможный «короткий путь» по форме листа
#            нейтрализуется ротационной аугментацией (см. ROTATION_AUG: каждый класс
#            получает сбалансированную смесь пропорций) и случайным цветом полей.
# squash:    растянуть в квадрат 224x224 (искажает содержимое — НЕ рекомендуется).
# 3_test_inference.py и 5_retrain.py должны использовать ТОТ ЖЕ режим.
RESIZE_MODE: str = "letterbox"
# Цвет полей letterbox в TRAIN: "white" | "black" | "gray" | "random".
