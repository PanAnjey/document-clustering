CLASS_WEIGHTS: str = "inverse_norm"
USE_AMP: bool = True                       # mixed precision
EARLY_STOP_PATIENCE: int = 5               # 0 = отключить

# ---- Вход модели: кроп текстовой области в высоком разрешении ----
# Ориентация определяется НАПРАВЛЕНИЕМ текста, а не формой листа. Чтобы модель
# «видела» символы (критично для 0 vs 180), вместо ужатой целой страницы берём
# текст-плотное окно из ПОЛНОГО разрешения и масштабируем к IMAGE_SIZE.
#   full -> вся страница (через RESIZE_MODE: letterbox) — ВЫБРАН как робастный для
#           гетерогенных данных (документы + паспорта + чертежи + фото): crop наводился
#           на не-текст/разнонаправленный текст у паспортов/чертежей.
#   crop -> кроп текст-плотного окна (хорош для чистых текст-документов, но ломается
#           на паспортах/чертежах) — оставлен под флагом для будущего роутинга.
# ВАЖНО: train / 5_retrain / 3_test_inference ОБЯЗАНЫ использовать один INPUT_MODE.
# Смена режима ТРЕБУЕТ ПЕРЕОБУЧЕНИЯ (модель с full несовместима с crop и наоборот).
