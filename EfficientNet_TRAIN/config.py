# ---- Адаптивный размер окна (устойчивость к неизвестному разрешению/DPI) ----
# Состав и разрешение будущих данных заранее НЕизвестны (другой месяц). Чтобы в
# финальном входе символы всегда были легибельны (~CROP_TARGET_GLYPH px) независимо
# от DPI, размер окна подбирается ПОД КАЖДОЕ изображение по измеренной высоте символа:
#   win = высота_символа_в_оригинале * IMAGE_SIZE / CROP_TARGET_GLYPH
#   (не меньше IMAGE_SIZE, не больше короткой стороны).
# Так низкоразрешённые сканы дают ~native кроп, а высокоразрешённые — окно крупнее
# (больше строк), и после ресайза глиф ~CROP_TARGET_GLYPH в обоих случаях.
CROP_ADAPTIVE: bool = True
CROP_TARGET_GLYPH: float = 14.0
# Фиксированный размер окна (px полного разрешения) — используется только при
# CROP_ADAPTIVE=False. Оценить: python estimate_crop_window.py [папка].
CROP_WINDOW: int = 240
# Длинная сторона уменьшенной копии для ПОИСКА текст-плотного окна (только скорость).
CROP_SEARCH_MAXSIDE: int = 800
# Случайный сдвиг центра окна (px полного разрешения) в TRAIN — регуляризация.
# В val и при инференсе сдвиг = 0 (детерминированно).
CROP_JITTER: int = 64
# ---- Гибридный вход: текст -> кроп, не-текст -> всё изображение ----
# Данные неоднородны (документы + чертежи/фото/паспорта). У не-текста читать нечего,
# поэтому кроп текст-окна бессмыслен — для таких изображений подаётся ВСЁ изображение
# (letterbox). Различие «текст/не-текст» — по числу «буквенных» компонент (дешёвая
# эвристика, без отдельного классификатора типов). Логика одинакова train/inference.
CROP_FALLBACK_FULL: bool = True
# Порог числа текст-компонент (на уменьшенной до CROP_SEARCH_MAXSIDE копии):
